export type MessageKey = keyof typeof messages.ko;

export const i18n = $state<{ locale: Locale; ready: boolean }>({ locale: fallback, ready: false });

export function normalizeLocale(value: string | null | undefined): Locale {
  const short = value?.toLowerCase().slice(0, 2);
  return supported.includes(short as Locale) ? short as Locale : fallback;
}

export function initLocale() {
  if (typeof window === 'undefined') return;
  const saved = localStorage.getItem('erp.ui.locale');
  i18n.locale = normalizeLocale(saved ?? fallback);
  i18n.ready = true;
  applyLocale();
}

export function setLocale(locale: Locale) {
  i18n.locale = locale;
  if (typeof window !== 'undefined') localStorage.setItem('erp.ui.locale', locale);
  applyLocale();
}

export function toggleLocale() {
  setLocale(i18n.locale === 'ko' ? 'en' : 'ko');
}

function applyLocale() {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = i18n.locale;
}

export function t(key: MessageKey, values?: Record<string, string | number>): string {
  let text: string = messages[i18n.locale][key] ?? messages[fallback][key] ?? key;
  if (values) for (const [name, value] of Object.entries(values)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}

export function localeTag(): string {
  return i18n.locale === 'ko' ? 'ko-KR' : 'en-US';
}
